#!/usr/bin/env python3
"""A project's language wiki: Markdown pages that agents and people both read and edit, next to the store.

The store (export/<project>/profile/*.json, docs/language-store.md) holds the facts the agents
work with (checked against the corpus; by the team only where marked); the
wiki (export/<project>/wiki/) holds the explanations: how a construction works, which models are best, what
was tried and rejected, open questions. Each page has

  ---
  title: Possession
  entries: [possessor, possessive_pronouns]     # store ids shown on this page; 'term:*' claims a kind
  kind: questions                               # optional: a page of numbered questions for the team (the viewer
                                                # lists them, as it does '> **Question …:**' / '> **Frage …:**' callouts)
  ---
  prose: free to edit, by agents and people
  <!-- store:begin ... -->  the page's store entries, generated by `sync`; never edit inside  <!-- store:end sha=… -->

An entry is shown on the page that names its id; ids claimed by no page name go to the page whose pattern
matches (`term:*`), and the rest to inbox.md, from where an editor moves them to a page's `entries`. To change
a fact, change the store (a new entry with `supersedes`); a person who doesn't edit JSON writes
`> **Correction (name, date):** …` on the page, and the next agent turns it into a store entry.

  python3 scripts/wiki.py init <project> --from-notes FILE --map FILE.json   seed pages from a notes file
  python3 scripts/wiki.py sync <project>    refresh the generated blocks, index.md and inbox.md
  python3 scripts/wiki.py lint <project>    links resolve, page ids exist, no edits inside generated blocks, and the
                                            quotations keep to docs/licensing.md (scripts/quotes.py)
  python3 scripts/wiki.py view <project> [--out FILE]   one offline HTML file to read the pages and search the
                                            store (default export/<project>/wiki-view.html; a generated copy:
                                            edits go into the .md pages)
"""
import fnmatch, hashlib, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
from project import project_dir  # noqa: E402
from verse_pack import load_profile  # noqa: E402
import gloss as G  # noqa: E402

BEGIN = "<!-- store:begin (generated by scripts/wiki.py sync from profile/; change the store, not this block) -->"
END_RX = re.compile(r"<!-- store:end sha=([0-9a-f]{8}) -->")
BLOCK_RX = re.compile(re.escape(BEGIN) + r"\n(.*?)\n<!-- store:end sha=[0-9a-f]{8} -->", re.S)
SPECIAL = ("index.md", "inbox.md", "log.md")


def sha(s):
    return hashlib.sha256(s.encode("utf-8")).hexdigest()[:8]


def read_page(path):
    """(frontmatter dict, body) of a page; the frontmatter knows title and entries only."""
    text = open(path, encoding="utf-8").read()
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    fm, body = {}, text
    if m:
        body = text[m.end():]
        for line in m[1].splitlines():
            k, _, v = line.partition(":")
            v = v.strip()
            if v.startswith("["):
                fm[k.strip()] = [x.strip().strip("'\"") for x in v.strip("[]").split(",") if x.strip()]
            else:
                fm[k.strip()] = v.strip("'\"")
    return fm, body


def write_page(path, fm, body):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    head = "---\n" + "".join(f"{k}: [{', '.join(v)}]\n" if isinstance(v, list) else f"{k}: {v}\n" for k, v in fm.items()) + "---\n"
    open(path, "w", encoding="utf-8").write(head + body)


def pages(wdir):
    out = []
    for dp, _, fs in os.walk(wdir):
        for f in sorted(fs):
            if f.endswith(".md"):
                rel = os.path.relpath(os.path.join(dp, f), wdir)
                out.append(rel)
    return sorted(out)


def render(e):
    v = e["value"] if isinstance(e["value"], str) else json.dumps(e["value"], ensure_ascii=False)
    head = f"- **`{e['id']}`**" + (f" {e['source']} →" if e.get("source") else "") + f" **{v}**"
    tags = [e.get("confidence", ""), e.get("status", "")] + ([e["attested"]] if e.get("attested") else [])
    if e.get("kind") == "morph":
        head += f" `{e.get('form')}` ({e.get('slot')}, {e.get('host')})"
    elif e.get("kind") == "cell":
        head += f" {e.get('paradigm')} {e.get('bundle')}" + (" (gap)" if e.get("gap") else "")
    elif e.get("kind") == "claim":
        tags.append(e.get("verdict", ""))
    elif e.get("kind") == "word":
        head += f" `{e.get('form')}` (a protected word: never split)"
    head += f" [{', '.join(t for t in tags if t)}]"
    if e.get("pattern"):
        head += f" — `{e['pattern']}`"
    ev = "; ".join(r["ref"] + (f" *{r['form']}*" if r.get("form") else "") for r in e.get("evidence", [])[:4])
    lines = [head]
    for g in G.glosses(e):
        lines.append(f"  - gloss: {G.line(g)}")
    if e.get("interlinear"):
        lines.append(f"  - interlinear: `{e['interlinear']}`")
    if ev:
        lines.append(f"  - NT: {ev}")
    if e.get("words"):
        lines.append(f"  - answers: {', '.join(e['words'])}")
    if e.get("figures"):
        lines.append(f"  - tested ({', '.join(e.get('tests', []))}): {e['figures']}")
    if e.get("next"):
        lines.append(f"  - next: {e['next']}")
    if e.get("note"):
        lines.append(f"  - {e['note']}")
    lines.append(f"  - {e.get('by', '')}, {e.get('date', '')}" + (f", supersedes `{e['supersedes']}`" if e.get("supersedes") else ""))
    return "\n".join(lines)


def block(entries):
    inner = "\n".join(render(e) for e in entries) if entries else "_(no store entries on this page)_"
    return f"{BEGIN}\n{inner}\n<!-- store:end sha={sha(inner)} -->"


def assign(wdir, live):
    """{page: [entries]} and the unplaced entries: explicit ids first, then patterns."""
    claims = {p: read_page(os.path.join(wdir, p))[0].get("entries", []) for p in pages(wdir) if p not in SPECIAL}
    byid = {e["id"]: e for e in live}
    placed, out = set(), {p: [] for p in claims}
    for p, ids in claims.items():
        for i in ids:
            if "*" not in i and i in byid and i not in placed:
                out[p].append(byid[i]); placed.add(i)
    for p, ids in claims.items():
        for i in ids:
            if "*" in i:
                for e in live:
                    if e["id"] not in placed and fnmatch.fnmatch(e["id"], i):
                        out[p].append(e); placed.add(e["id"])
    # a refinement (supersedes / id.N) goes with the page of what it refines
    for e in live:
        if e["id"] in placed:
            continue
        base = e.get("supersedes") or re.sub(r"\.\d+$", "", e["id"])
        for p, es in out.items():
            if base in claims[p] or any(x["id"] == base or x["id"].startswith(base + ".") for x in es):
                es.append(e); placed.add(e["id"]); break
    return out, [e for e in live if e["id"] not in placed], claims


def sync(pname):
    pdir = project_dir(pname)
    wdir = os.path.join(pdir, "wiki")
    live = load_profile(os.path.join(pdir, "profile"))
    out, unplaced, _ = assign(wdir, live)
    for p, es in out.items():
        path = os.path.join(wdir, p)
        fm, body = read_page(path)
        b = block(es)
        if not BLOCK_RX.search(body) and fm.get("kind") == "team-input" and "\n## Items" in body:
            # the team appends items at the end: the generated block goes before them (scripts/team_input.py)
            body = body.replace("\n## Items", "\n## Store entries\n\n" + b + "\n\n## Items", 1)
        else:
            body = BLOCK_RX.sub(lambda m: b, body) if BLOCK_RX.search(body) else body.rstrip() + "\n\n## Store entries\n\n" + b + "\n"
        write_page(path, fm, body)
    inbox = os.path.join(wdir, "inbox.md")
    ib = ("Store entries that no page claims yet. Move each id into the `entries:` of the page it belongs to "
          "(or start a page), then run `python3 scripts/wiki.py sync " + pname + "`.\n\n" + block(unplaced) + "\n")
    write_page(inbox, {"title": "Inbox"}, ib)
    idx = os.path.join(wdir, "index.md")
    fm, body = read_page(idx) if os.path.exists(idx) else ({"title": "Index"}, "")
    rows = []
    for p in pages(wdir):
        if p in SPECIAL:
            continue
        t = read_page(os.path.join(wdir, p))[0].get("title", p)
        rows.append(f"- [{t}]({p}) — {len(out.get(p, []))} store entries")
    rows.append(f"- [Inbox](inbox.md) — {len(unplaced)} unplaced entries")
    rows.append("- [Log](log.md) — who changed what, newest last")
    b = f"{BEGIN}\n" + "\n".join(rows) + f"\n<!-- store:end sha={sha(chr(10).join(rows))} -->"
    body = BLOCK_RX.sub(lambda m: b, body) if BLOCK_RX.search(body) else body.rstrip() + "\n\n## Pages\n\n" + b + "\n"
    write_page(idx, fm, body)
    print(f"{wdir}: {len(out)} pages, {sum(len(v) for v in out.values())} entries placed, {len(unplaced)} in the inbox")


def lint(pname):
    pdir = project_dir(pname)
    wdir = os.path.join(pdir, "wiki")
    live = {e["id"] for fn in ("observations.json", "decisions.json") if os.path.exists(os.path.join(pdir, "profile", fn))
            for e in json.load(open(os.path.join(pdir, "profile", fn), encoding="utf-8"))["entries"]}
    problems = []
    for p in pages(wdir):
        fm, body = read_page(os.path.join(wdir, p))
        for i in fm.get("entries", []):
            if "*" not in i and i not in live:
                problems.append(f"{p}: entries names {i}, which is not in the store")
        for m in BLOCK_RX.finditer(body):
            inner, end = m[1], END_RX.search(m[0])
            if end and end[1] != sha(inner):
                problems.append(f"{p}: the generated block was edited by hand (change the store, then sync)")
        for link in re.findall(r"\]\(([^)#\s]+\.md)(?:#[^)]*)?\)", body):
            if not os.path.exists(os.path.normpath(os.path.join(wdir, os.path.dirname(p), link))):
                problems.append(f"{p}: link to {link} does not resolve")
    try:                                   # quotations from the editions (docs/licensing.md)
        import quotes
        Q = quotes.Quotes(pname)
        qp, qw, total = Q.check_files([os.path.join(wdir, p) for p in pages(wdir)])
        problems += qp
        notes = [f"warning: {w}" for w in qw] + [f"quotations: {total} words, {100 * total / max(Q.words, 1):.2f}% of the edition"]
    except ImportError as e:
        notes = [f"warning: quotations not checked ({e})"]
    print("\n".join(problems + notes) if problems else "\n".join(notes + [f"{wdir}: {len(pages(wdir))} pages, 0 problems"]))
    return not problems


def init(pname, notes, mapping):
    """Seed pages from a notes file split at '## ' headings; mapping {heading number: {file, title, entries}}."""
    wdir = os.path.join(project_dir(pname), "wiki")
    os.makedirs(wdir, exist_ok=True)
    text = open(notes, encoding="utf-8").read()
    parts = re.split(r"^## (\d+)\. (.*)$", text, flags=re.M)
    m = json.load(open(mapping, encoding="utf-8"))
    intro = parts[0].split("\n", 1)[1].strip()
    seen = {}
    for i in range(1, len(parts) - 1, 3):
        num, head, body = parts[i], parts[i + 1].strip(), parts[i + 2].strip()
        spec = m["sections"][num]
        seen.setdefault(spec["file"], {"title": spec["title"], "entries": spec.get("entries", []), "body": []})
        seen[spec["file"]]["body"].append((head, body))
    for f, spec in list(seen.items()) + [(f, s | {"body": []}) for f, s in m.get("extra", {}).items() if f not in seen]:
        path = os.path.join(wdir, f)
        if os.path.exists(path):
            continue
        body = "".join((f"{b}\n\n" if h in spec["title"] else f"## {h}\n\n{b}\n\n") for h, b in spec["body"]) or (spec.get("intro", "") + "\n\n")
        write_page(path, {"title": spec["title"], "entries": spec["entries"]}, f"# {spec['title']}\n\n" + body)
    if not os.path.exists(os.path.join(wdir, "index.md")):
        write_page(os.path.join(wdir, "index.md"), {"title": m["title"]}, f"# {m['title']}\n\n{m.get('intro', '')}\n\n{intro}\n")
    if not os.path.exists(os.path.join(wdir, "log.md")):
        write_page(os.path.join(wdir, "log.md"), {"title": "Log"},
                   "# Log\n\nOne line per change, newest last: date, who (agent:<chapter> or a name), what.\n\n" + "".join(f"- {l}\n" for l in m.get("log", [])))
    sync(pname)


def md_html(text, page):
    """A small Markdown renderer for the wiki pages (headings, lists, tables, quotes, emphasis, code, links)."""
    import html as H

    def inline(s):
        s = H.escape(s, quote=False)
        s = re.sub(r"`([^`]+)`", r"<code>\1</code>", s)
        s = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", s)
        s = re.sub(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", r"<em>\1</em>", s)

        def link(m):
            t, u = m[1], m[2]
            if re.match(r"[^:]+\.md(#.*)?$", u):
                target = os.path.normpath(os.path.join(os.path.dirname(page), u.split("#")[0])).replace(os.sep, "/")
                return f'<a href="#{target}">{t}</a>'
            return f'<a href="{u}">{t}</a>' if u.startswith("http") else f'<span class="path">{t}</span>'
        return re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", link, s)

    out, lines, i = [], text.splitlines(), 0
    while i < len(lines):
        l = lines[i]
        if l.startswith("<!-- store:begin"):
            out.append('<div class="store-block"><div class="store-label">Store entries (generated from profile/)</div>')
            i += 1
            continue
        if l.startswith("<!-- store:end"):
            out.append("</div>")
            i += 1
            continue
        if not l.strip():
            i += 1
            continue
        if l.startswith("```"):
            j = i + 1
            while j < len(lines) and not lines[j].startswith("```"):
                j += 1
            out.append("<pre>" + H.escape("\n".join(lines[i + 1:j])) + "</pre>")
            i = j + 1
            continue
        m = re.match(r"(#{1,4}) (.*)", l)
        if m:
            n = len(m[1])
            out.append(f"<h{n}>{inline(m[2])}</h{n}>")
            i += 1
            continue
        if l.startswith(">"):
            q = []
            while i < len(lines) and lines[i].startswith(">"):
                q.append(lines[i][1:].strip())
                i += 1
            body = " ".join(q)
            cls = "question" if "Question for" in body else "correction" if "Correction" in body else "quote"
            out.append(f'<blockquote class="{cls}">{inline(body)}</blockquote>')
            continue
        if l.startswith("|"):
            rows = []
            while i < len(lines) and lines[i].startswith("|"):
                if not re.match(r"^\|[\s:|-]+\|$", lines[i]):
                    rows.append([c.strip() for c in lines[i].strip("|").split("|")])
                i += 1
            t = "<table>" + "".join("<tr>" + "".join(f"<{'th' if k == 0 else 'td'}>{inline(c)}</{'th' if k == 0 else 'td'}>" for c in r) + "</tr>"
                                    for k, r in enumerate(rows)) + "</table>"
            out.append(f'<div class="table-wrap">{t}</div>')
            continue
        if re.match(r"\s*([-*]|\d+\.) ", l):
            items = []                       # (depth, text, ordered)
            while i < len(lines) and lines[i].strip():
                m = re.match(r"(\s*)([-*]|\d+\.) (.*)", lines[i])
                if m:
                    items.append([len(m[1]) // 2, m[3], m[2][0].isdigit()])
                elif items:
                    items[-1][1] += " " + lines[i].strip()
                i += 1
            stack, h = [], []
            for d, t, ordered in items:
                while len(stack) > d + 1:
                    h.append(f"</li></{stack.pop()}>")
                if len(stack) < d + 1:
                    while len(stack) < d + 1:
                        tag = "ol" if ordered else "ul"
                        stack.append(tag)
                        h.append(f"<{tag}>")
                else:
                    h.append("</li>")
                h.append("<li>" + inline(t))
            while stack:
                h.append(f"</li></{stack.pop()}>")
            out.append("".join(h))
            continue
        p = []
        while i < len(lines) and lines[i].strip() and not re.match(r"(#{1,4} |>|\||```|\s*([-*]|\d+\.) |<!--)", lines[i]):
            p.append(lines[i].strip())
            i += 1
        out.append("<p>" + inline(" ".join(p)) + "</p>")
    return "\n".join(out)


NOTICE = ("Working analysis by AI agents, learned from the existing translation: hypotheses for the drafts, not checked "
          "by the language team. Only entries marked “team” come from the team.")


def view(pname, out_file, notice=None):
    """One self-contained HTML file to read the wiki and browse the store, offline; nothing is sent anywhere. Every page
    and the store open with the notice (what the memory is and who has checked it: NOTICE, or the site's text in the
    team's school language), and each entry says whether it comes from the team."""
    pdir = project_dir(pname)
    wdir = os.path.join(pdir, "wiki")
    entries = []
    for fn in ("observations.json", "decisions.json"):
        f = os.path.join(pdir, "profile", fn)
        if os.path.exists(f):
            entries += json.load(open(f, encoding="utf-8"))["entries"]
    live = {e["id"] for e in load_profile(os.path.join(pdir, "profile"))}
    placed, _, _ = assign(wdir, load_profile(os.path.join(pdir, "profile")))
    where = {e["id"]: p for p, es in placed.items() for e in es}
    store = [{k: e.get(k) for k in ("id", "kind", "source", "value", "pattern", "note", "words", "confidence", "status",
                                    "attested", "method", "by", "date", "supersedes")} |
             {"team": e.get("method") == "team-decision" or str(e.get("by") or "").startswith("team:")} |
             {"refs": [r.get("ref", "") + (f" {r['form']}" if r.get("form") else "") for r in e.get("evidence", []) if isinstance(r, dict)],
              "live": e["id"] in live and e.get("status") != "superseded", "page": where.get(e["id"]),
              "glosses": [G.line(g) for g in G.glosses(e)] if e["id"] in live else []} for e in entries]
    order = ["index.md"] + [p for p in pages(wdir) if p not in SPECIAL] + ["inbox.md", "log.md"]
    pg, questions = [], []
    for p in order:
        if not os.path.exists(os.path.join(wdir, p)):
            continue
        fm, body = read_page(os.path.join(wdir, p))
        pg.append({"id": p, "title": fm.get("title", p), "html": md_html(body, p), "text": re.sub(r"\s+", " ", body)})
        for m in re.finditer(r"^> \*\*(?:Question|Frage|Spørgsmål)[^*]*:\*\*(.*(?:\n>.*)*)", body, re.M):
            questions.append({"page": p, "title": fm.get("title", p), "html": md_html("> " + m[0][2:], p)})
        if fm.get("kind") == "questions":     # a page of numbered questions for the team
            for m in re.finditer(r"^\d+\. (.*(?:\n   .*)*)", body, re.M):
                questions.append({"page": p, "title": fm.get("title", p), "html": md_html(m[1], p)})
    cf = os.path.join(pdir, "CREDITS.md")
    credits = md_html(read_page(cf)[1], "CREDITS.md") if os.path.exists(cf) else ""
    data = json.dumps({"project": pname, "pages": pg, "store": store, "questions": questions, "credits": credits,
                       "notice": notice or NOTICE}, ensure_ascii=False)
    tpl = open(os.path.join(ROOT, "scripts", "wiki_view.html"), encoding="utf-8").read()
    html = tpl.replace("/*DATA*/null", data.replace("</", "<\\/")).replace("{{project}}", pname)
    open(out_file, "w", encoding="utf-8").write(html)
    print(f"{os.path.relpath(out_file, ROOT)}: {len(pg)} pages, {len(store)} store entries ({len(live)} live), "
          f"{len(questions)} open questions")


def main():
    a = sys.argv[1:]
    if len(a) < 2:
        raise SystemExit(__doc__)
    cmd, pname = a[0], a[1]
    if cmd == "sync":
        sync(pname)
    elif cmd == "view":
        view(pname, a[a.index("--out") + 1] if "--out" in a else os.path.join(project_dir(pname), "wiki-view.html"))
    elif cmd == "lint":
        sys.exit(0 if lint(pname) else 1)
    elif cmd == "init":
        init(pname, a[a.index("--from-notes") + 1], a[a.index("--map") + 1])
    else:
        raise SystemExit(__doc__)


if __name__ == "__main__":
    main()
